// Single source of truth: skills/*/SKILL.md (+ references).
// Generates src/skills.inline.ts for runtimes without a filesystem (Workers).
import { readdir, readFile, writeFile, stat } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..", "skills");
const OUT = path.resolve(import.meta.dirname, "..", "src", "skills.inline.ts");
const TEXT_EXTS = new Set([".md", ".txt", ".json", ".yaml", ".yml"]);

async function walk(dir, base = "") {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = {};
  for (const e of entries) {
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) Object.assign(files, await walk(path.join(dir, e.name), rel));
    else if (e.isFile()) {
      if (!TEXT_EXTS.has(path.extname(e.name))) {
        console.warn(`inline-skills: skipping non-text file ${rel}`);
        continue;
      }
      files[rel] = await readFile(path.join(dir, e.name), "utf8");
    }
  }
  return files;
}

const files = await walk(ROOT);
await stat(ROOT).catch(() => {
  throw new Error("skills/ directory not found");
});
const out =
  `// Generated by scripts/inline-skills.mjs — edit skills/*/SKILL.md instead.\n` +
  `export const SKILL_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`;
await writeFile(OUT, out);
console.log(`inline-skills: ${Object.keys(files).length} file(s) -> src/skills.inline.ts`);
